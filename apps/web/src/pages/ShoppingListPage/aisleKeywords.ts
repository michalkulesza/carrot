// Keywords are lowercase, accent-free (see normalizeItemText) and cover
// en / pl / de / fr / es. Matching rules:
//   "word"   matches at the start of a word ("lemon" -> "lemons")
//   "word$"  matches the whole word only ("ice$" does not match "rice")
//   "*word"  matches anywhere inside a word (German compounds: "*kase")
// Stages are tried in order and the first match wins, so specific phrases
// ("peanut butter", "coconut milk") sit in earlier stages than the broad
// words they contain ("butter", "milk").

export interface AisleStage {
  category: ShoppingCategory
  words: string[]
}

